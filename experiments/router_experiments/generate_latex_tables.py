#!/usr/bin/env python3
"""
generate_latex_tables.py
Reads canonical_results.json and emits ready-to-paste LaTeX for the paper's main table
plus a headroom-capture table.

Every claim in the captions is derived from the numbers in the JSON rather than written by
hand. The previous version hard-coded three assertions that the results contradict -- that
RL-Route "matches or slightly exceeds the best tuned supervised methods", that it is
"uniquely capable of online adaptation", and that the metric is MRR@5 when the run records
untruncated reciprocal rank -- and it bolded RL-Route whenever it merely beat Gradient
Boosting, which on HotpotQA bolded a difference with p = 0.354. Captions that are generated
cannot drift away from the table the way hand-written ones did.
"""

import os
import sys
import json

PROJECT_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RESULTS_PATH = os.path.join(PROJECT_ROOT, "results", "canonical_results.json")
OUTPUT_PATH = os.path.join(PROJECT_ROOT, "results", "main_results_table.tex")

NON_ORACLE = ["bm25", "dense", "hybrid", "score_gap", "logistic_regression",
              "random_forest", "ridge", "gradient_boosting", "rl_route_mean"]


def metric_caption(data):
    """Describe the metric from the run's own provenance, not from a hard-coded string."""
    try:
        m = data["_provenance"]["datasets"][next(iter(data["_provenance"]["datasets"]))]["metric"]
        return m["name"].upper(), m["means"]
    except (KeyError, StopIteration, TypeError):
        return "reward", "metric semantics unavailable -- provenance missing from results file"


def best_non_oracle(row):
    """Highest non-oracle value in a column, so bolding tracks the table and not a narrative."""
    vals = [(k, row[k]) for k in NON_ORACLE if isinstance(row.get(k), (int, float))]
    return max(vals, key=lambda kv: kv[1])[0] if vals else None


def main():
    if not os.path.exists(RESULTS_PATH):
        print(f"Error: {RESULTS_PATH} not found. Run canonical_evaluation.py first.")
        return

    with open(RESULTS_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)

    # Order of datasets in the table
    datasets = ["nq", "triviaqa", "hotpotqa"]
    
    # Check what datasets actually exist in the results
    datasets = [ds for ds in datasets if ds in data]
    
    if not datasets:
        print("Error: No dataset results found in JSON.")
        return

    # Define the baseline methods we want to show
    rows = {
        "bm25": "Always BM25",
        "dense": "Always Dense",
        "hybrid": "Always Hybrid",
        "score_gap": "Heuristic (Score Gap)",
        "logistic_regression": "Logistic Regression",
        "random_forest": "Random Forest",
        "ridge": "Ridge Regression",
        "gradient_boosting": "Gradient Boosting (Tuned)"
    }

    metric_name, metric_means = metric_caption(data)
    n_seeds = len(data.get("_provenance", {}).get("seeds", []) or [])
    winners = {ds: best_non_oracle(data[ds]) for ds in datasets}

    # State the outcome the numbers actually support: on how many datasets does the proposed
    # router beat the best fixed retriever, and is any such win significant?
    beats, sig_wins = [], []
    for ds in datasets:
        s = data[ds].get("significance_vs_best_fixed") or {}
        delta, p = s.get("delta"), s.get("p_value")
        if delta is None:
            continue
        if delta > 0:
            beats.append(ds)
            if p is not None and p < 0.05:
                sig_wins.append(ds)
    finding = (
        f"RL-Route exceeds the best fixed retriever on "
        f"{len(beats)} of {len(datasets)} datasets"
        + (f" ({', '.join(d.upper() for d in beats)})" if beats else "")
        + ", and on "
        + (f"{len(sig_wins)}" if sig_wins else "none")
        + " of these is the difference significant at $p<0.05$"
        + (f" ({', '.join(d.upper() for d in sig_wins)})" if sig_wins else "")
        + "."
    )

    latex = []
    latex.append("% Auto-generated by generate_latex_tables.py -- do not edit by hand.")
    latex.append(f"% Captions are derived from the results file; metric: {metric_means}")
    latex.append(r"\begin{table}[h]")
    latex.append(r"\centering")
    latex.append(
        r"\caption{Main results: mean " + metric_name + " on the fixed test split, measured as "
        + metric_means + ". " + finding
        + r" Bold marks the highest non-oracle value in each column; it does not imply "
        + r"statistical significance. RL-Route is reported as mean $\pm$ std across "
        + (f"{n_seeds}" if n_seeds else "multiple") + r" training seeds, so its spread "
        + r"reflects seed variance only and not variation across data splits.}")
    latex.append(r"\label{tab:main_results}")
    
    # Column formatting: Model + one column per dataset
    col_def = "l" + "c" * len(datasets)
    latex.append(r"\begin{tabular}{" + col_def + "}")
    latex.append(r"\toprule")
    
    # Header row
    ds_headers = [ds.upper() for ds in datasets]
    latex.append(r"\textbf{Routing Strategy} & " + " & ".join([f"\\textbf{{{h}}}" for h in ds_headers]) + r" \\")
    latex.append(r"\midrule")
    
    def cell(ds, key, value):
        """Bold iff this key is the column's highest non-oracle value."""
        txt = f"{value:.4f}"
        return f"\\textbf{{{txt}}}" if winners.get(ds) == key else txt

    # Group 1: Static Baselines
    latex.append(r"\textit{Static Baselines} & " + " & " * (len(datasets)-1) + r" \\")
    for key in ["bm25", "dense", "hybrid"]:
        if key in rows:
            scores = [cell(ds, key, data[ds].get(key, 0.0)) for ds in datasets]
            latex.append(f"{rows[key]} & " + " & ".join(scores) + r" \\")

    latex.append(r"\midrule")

    # Group 2: Heuristic & Supervised Classifiers
    latex.append(r"\textit{Supervised Classifiers (Frozen)} & " + " & " * (len(datasets)-1) + r" \\")
    for key in ["score_gap", "logistic_regression", "random_forest", "ridge", "gradient_boosting"]:
        if key in rows:
            scores = [cell(ds, key, data[ds].get(key, 0.0)) for ds in datasets]
            latex.append(f"{rows[key]} & " + " & ".join(scores) + r" \\")

    latex.append(r"\midrule")

    # Group 3: Reinforcement Learning (Ours)
    latex.append(r"\textit{Reinforcement Learning (Adaptive)} & " + " & " * (len(datasets)-1) + r" \\")
    rl_scores = []
    for ds in datasets:
        mean = data[ds].get("rl_route_mean", 0.0)
        std = data[ds].get("rl_route_std", 0.0)
        rl_scores.append(f"{cell(ds, 'rl_route_mean', mean)} $\\pm$ {std:.4f}")

    latex.append(r"RL-Route (Ours) & " + " & ".join(rl_scores) + r" \\")
    
    latex.append(r"\midrule")
    
    # Group 4: Oracle Bound
    oracle_scores = [f"{data[ds].get('oracle', 0.0):.4f}" for ds in datasets]
    latex.append(r"\textit{Oracle Upper Bound} & " + " & ".join(oracle_scores) + r" \\")
    
    latex.append(r"\bottomrule")
    latex.append(r"\end{tabular}")
    latex.append(r"\end{table}")

    # ---- Table 2: headroom capture -------------------------------------------------
    # The absolute rewards in Table 1 make it hard to see that every method lands on the
    # best fixed arm. Capture normalises each method onto [best_fixed -> oracle], so 0%
    # means "no better than committing to one retriever" and 100% means "matches the
    # oracle". Negative means actively worse than committing.
    latex.append("")
    latex.append(r"\begin{table}[h]")
    latex.append(r"\centering")
    latex.append(
        r"\caption{Oracle headroom capture: $(\text{method} - \text{best fixed}) / "
        r"(\text{oracle} - \text{best fixed})$, in percent. $0\%$ is indistinguishable from "
        r"committing to the single best retriever and $100\%$ would match the per-query "
        r"oracle; negative values are worse than committing. Every learned method sits near "
        r"zero, which is the collapse-to-best-fixed result stated in normalised form.}")
    latex.append(r"\label{tab:headroom_capture}")
    latex.append(r"\begin{tabular}{l" + "r" * len(datasets) + "}")
    latex.append(r"\toprule")
    latex.append(r"\textbf{Routing Strategy} & "
                 + " & ".join([f"\\textbf{{{ds.upper()}}}" for ds in datasets]) + r" \\")
    latex.append(r"\midrule")

    hr = {}
    for ds in datasets:
        row = data[ds]
        bf = max(row.get(k, 0.0) for k in ("bm25", "dense", "hybrid"))
        hr[ds] = (bf, row.get("oracle", 0.0) - bf)

    capture_rows = [("score_gap", rows["score_gap"]),
                    ("logistic_regression", rows["logistic_regression"]),
                    ("ridge", rows["ridge"]),
                    ("random_forest", rows["random_forest"]),
                    ("gradient_boosting", rows["gradient_boosting"]),
                    ("rl_route_mean", "RL-Route (Ours)")]
    for key, label in capture_rows:
        cells = []
        for ds in datasets:
            bf, head = hr[ds]
            v = data[ds].get(key)
            cells.append("---" if v is None or head <= 0
                         else f"{100.0 * (v - bf) / head:+.1f}\\%")
        latex.append(f"{label} & " + " & ".join(cells) + r" \\")

    latex.append(r"\midrule")
    latex.append(r"\textit{Absolute headroom} & "
                 + " & ".join([f"{hr[ds][1]:.4f}" for ds in datasets]) + r" \\")
    latex.append(r"\bottomrule")
    latex.append(r"\end{tabular}")
    latex.append(r"\end{table}")

    latex_string = "\n".join(latex)
    
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(latex_string)
        
    print(f"Generated LaTeX table saved to: {OUTPUT_PATH}")
    print("\n--- PREVIEW ---")
    print(latex_string)
    print("-----------------")

if __name__ == "__main__":
    main()
